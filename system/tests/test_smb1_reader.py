def test_noop_roundtrip_preserves_tile_count(rom_path: pathlib.Path, tmp_path: pathlib.Path):
    """A no-op export/import roundtrip yields the same tile count."""
    # Export player frame 0 (big walking frame 1)
    result = smb1_reader.export_player_frames(str(rom_path), str(tmp_path), scale=4)
    frame0 = result["frames"][0]
    tiles = frame0["tiles"]
    # Big walking frame 1 should be tiles 0x00-0x07
    assert tiles == [0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07]
    assert len(tiles) == 8


def test_inventory_manifest_matches_reader(rom_path: pathlib.Path, tmp_path: pathlib.Path):
    """The reader output aligns with the inventory manifest."""
    from gbox.smb1_inventory import build_inventory

    inv = build_inventory(str(rom_path), SOURCE_SHA256)
    result = smb1_reader.export_player_frames(str(rom_path), str(tmp_path), scale=1)
    assert len(result["frames"]) == len(inv["characters"]["player"]["frames"])


# --- Writer stage: no-op CHR tile roundtrip + collection registration ---

def test_tile_bytes_is_inverse_of_tile_pixels():
    """A decoded tile re-encodes to its original 16 bytes (bitplane roundtrip)."""
    from gbox.smb1_inventory import tile_pixels

    # A hand-built 8x8 pattern not generated by the parser: independent fixture.
    # checkerboard of indices 0..3 across two rows, plus a solid region.
    pixels = []
    for y in range(8):
        for x in range(8):
            pixels.append((x >> 1) & 0x3)  # 0,0,1,1,0,0,1,1 per row
    encoded = smb1_reader.tile_bytes(pixels)
    assert len(encoded) == 16
    assert smb1_reader.tile_bytes(tile_pixels(encoded, 0)) == encoded
    # Re-decode returns the identical index pattern
    assert tile_pixels(encoded, 0) == pixels


def test_roundtrip_tiles_is_byte_identical(rom_path: pathlib.Path):
    """All 512 CHR tiles re-encode to the exact ROM bytes (no-op proof)."""
    result = smb1_reader.roundtrip_tiles(str(rom_path))
    assert result["tiles"] == 512
    assert result["mismatches"] == 0
    assert result["identical"] is True


def test_build_donor_patch_changes_tile(rom_path: pathlib.Path):
    """A changed donor produces bytes differing from the original tile."""
    from gbox.smb1_inventory import tile_pixels

    rom_data = open(rom_path, "rb").read()
    h = smb1_reader.parse_header(rom_data)
    chr_ = rom_data[h["chr_offset"]: h["chr_offset"] + h["chr_bytes"]]
    # tile 0 pixels, then flip one corner pixel
    orig_pixels = tile_pixels(chr_, 0)
    changed = list(orig_pixels)
    changed[0] = (changed[0] + 1) & 0x3
    patch = smb1_reader.build_donor_patch(str(rom_path), "player", 0, 0, changed)
    assert patch["changed"] is True
    assert patch["patched"] != patch["original"]
    # an unchanged donor is correctly reported as not changed
    same = smb1_reader.build_donor_patch(str(rom_path), "player", 0, 0, orig_pixels)
    assert same["changed"] is False


def test_roster_and_extract_run():
    """Collection-path registration exposes roster and a runnable entry point."""
    r = smb1_reader.roster()
    assert len(r) == 3
    slugs = {e["slug"] for e in r}
    assert slugs == {"smb1_mario", "smb1_luigi", "smb1_goomba"}
    assert smb1_reader.READER_VERSION == "smb1_reader/1"
    # no ROM path -> graceful error with roster attached
    missing = smb1_reader.extract_run({}, {"rom": "/nonexistent.nes"}, {}, "")
    assert "error" in missing and missing["roster"] == r


# --- Collection registration (characters.DEDICATED) ---

def test_characters_routes_smb1_to_the_reader():
    from gbox import characters
    from gbox.char_coverage import extractor_for
    game = {"game_id": "49b6a2f65aca26a2", "title": "Super Mario Bros. (nes)",
            "platform": "nes"}
    pick = lambda t, p: next((r[0] for r in characters.DEDICATED if r[1](t.lower(), p)), None)
    assert pick("super mario bros (nes)", "nes") == "smb1"
    # negative: SM64 must still route to sm64, not smb1
    assert pick("super mario 64", "n64") == "sm64"
    # extractor_for returns the reader + character roster
    name, roster = extractor_for(game)
    assert name == "smb1"
    assert {r["slug"] for r in roster} == {"smb1_mario", "smb1_luigi", "smb1_goomba"}
