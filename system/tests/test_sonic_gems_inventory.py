import hashlib
import os
import struct
import sys
import tempfile
import unittest

sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "gbox"))
import sonic_gems_inventory as sgi  # noqa: E402

SECTOR = 2048


def dir_record(name, lba, size, is_dir, namelen=None):
    """One ISO9660 directory record: 33-byte fixed part + name (name len at byte 32)."""
    raw = name.encode("latin-1") if isinstance(name, str) else name
    nl = namelen if namelen is not None else len(raw)
    ln = 33 + nl
    rec = bytearray(ln)
    rec[0] = ln
    rec[1] = 0
    struct.pack_into("<I", rec, 2, lba)
    struct.pack_into(">I", rec, 6, lba)
    struct.pack_into("<I", rec, 10, size)
    struct.pack_into(">I", rec, 14, size)
    rec[25] = 0x02 if is_dir else 0x00
    rec[32] = nl
    if raw:
        rec[33:33 + nl] = raw[:nl]
    return bytes(rec)


def build_iso(path, gc_base=True):
    """Hand-built ISO9660 image: PVD at sector 16, root dir lba 20, DATA dir lba 21, file lba 30."""
    base = 0x8000 if gc_base else 0
    pvd = bytearray(SECTOR)
    pvd[0] = 1
    pvd[1:6] = b"CD001"
    pvd[6] = 1
    pvd[40:44] = b"SGIJ"
    root = dir_record(b"\x00", 20, SECTOR, True, namelen=1)
    assert len(root) == 34
    pvd[156:156 + len(root)] = root
    rootdir = bytearray(SECTOR)
    off = 0
    for rec in (dir_record(b"\x00", 20, SECTOR, True, namelen=1),
                dir_record(b"\x01", 20, SECTOR, True, namelen=1),
                dir_record("DATA", 21, SECTOR, True)):
        rootdir[off:off + len(rec)] = rec
        off += len(rec)
    datadir = bytearray(SECTOR)
    rec = dir_record("TEST.BIN", 30, 1234, False)
    datadir[0:len(rec)] = rec
    with open(path, "wb") as f:
        f.truncate(base + 40 * SECTOR)
        f.seek(base + 16 * SECTOR)
        f.write(bytes(pvd))
        f.seek(base + 20 * SECTOR)
        f.write(bytes(rootdir))
        f.seek(base + 21 * SECTOR)
        f.write(bytes(datadir))
        f.seek(base + 30 * SECTOR)
        f.write(b"SONIC" * 100)
    return base


class TestInventory(unittest.TestCase):
    def test_finds_pvd_at_gamecube_base(self):
        with tempfile.TemporaryDirectory() as d:
            p = os.path.join(d, "disc.iso")
            base = build_iso(p, gc_base=True)
            with open(p, "rb") as f:
                b, pvd = sgi.find_pvd(f)
            self.assertEqual(b, base)
            self.assertEqual(pvd[1:6], b"CD001")

    def test_walk_lists_nested_file_with_size_and_offset(self):
        with tempfile.TemporaryDirectory() as d:
            p = os.path.join(d, "disc.iso")
            base = build_iso(p, gc_base=True)
            b, entries = sgi.walk_iso9660(p)
            self.assertEqual(b, base)
            self.assertEqual([e["path"] for e in entries], ["DATA/TEST.BIN"])
            self.assertEqual(entries[0]["size"], 1234)
            self.assertEqual(entries[0]["offset"], base + 30 * SECTOR)

    def test_afs_table_parses_count_and_members(self):
        with tempfile.TemporaryDirectory() as d:
            p = os.path.join(d, "a.afs")
            body = b"PLAY" + b"\x00" * 28
            with open(p, "wb") as f:
                f.write(b"AFS\x00" + struct.pack("<I", 2))
                f.write(struct.pack("<II", 24, len(body)))
                f.write(struct.pack("<II", 24 + len(body), 8))
                f.write(body + b"PLAY2\x00\x00\x00")
            with open(p, "rb") as f:
                t = sgi.afs_table(f, 0, os.path.getsize(p))
            self.assertIsNotNone(t)
            self.assertEqual(t["count"], 2)
            self.assertTrue(t["ok"])
            self.assertEqual(t["sizes"][0], len(body))
            self.assertEqual(t["offsets"][1], 24 + len(body))

    def test_afs_table_rejects_non_afs(self):
        with tempfile.TemporaryDirectory() as d:
            p = os.path.join(d, "x.bin")
            open(p, "wb").write(b"PLAY\x00" + b"\x00" * 64)
            with open(p, "rb") as f:
                self.assertIsNone(sgi.afs_table(f, 0, os.path.getsize(p)))

    def test_afs_table_flags_out_of_range_member(self):
        with tempfile.TemporaryDirectory() as d:
            p = os.path.join(d, "a.afs")
            with open(p, "wb") as f:
                f.write(b"AFS\x00" + struct.pack("<I", 1))
                f.write(struct.pack("<II", 16, 999999))
                f.write(b"\x00" * 8)
            with open(p, "rb") as f:
                t = sgi.afs_table(f, 0, os.path.getsize(p))
            self.assertFalse(t["ok"])

    def test_sha256_stream_matches_content(self):
        with tempfile.TemporaryDirectory() as d:
            p = os.path.join(d, "a.bin")
            data = b"sonic" * 1000
            open(p, "wb").write(data)
            self.assertEqual(sgi.sha256_stream(p), hashlib.sha256(data).hexdigest())

    def test_disc_header_fields(self):
        with tempfile.TemporaryDirectory() as d:
            p = os.path.join(d, "d.iso")
            hdr = bytearray(0x440)
            hdr[0:4] = b"G2XE"
            hdr[4] = 0x08
            hdr[5:8] = b"8P"
            hdr[8:10] = b"00"
            hdr[0x20:0x2A] = b"SONIC GEMS"
            open(p, "wb").write(bytes(hdr) + b"\x00" * 1024)
            h = sgi.disc_header(p)
            self.assertEqual(h[0:4], b"G2XE")
            self.assertEqual(h[0x20:0x2A], b"SONIC GEMS")

    def test_magic_census_counts_extensions(self):
        with tempfile.TemporaryDirectory() as d:
            p = os.path.join(d, "disc.iso")
            build_iso(p, gc_base=True)
            base, entries = sgi.walk_iso9660(p)
            c = sgi.magic_census(p, entries)
            self.assertEqual(c["extensions"][".bin"], 1)


if __name__ == "__main__":
    unittest.main(verbosity=2)


def _gcm_fixture(tmp_path):
    import struct
    img = bytearray(0x3000)
    img[0:6] = b"G2XE8P"
    names = b"\0DATA\0A.BIN\0"          # root(0) / DATA at 1 / A.BIN at 6
    ents = struct.pack(">BBHII", 1, 0, 0, 0, 3)          # root, next=3
    ents += struct.pack(">B", 1) + (1).to_bytes(3, "big") + struct.pack(">II", 0, 3)  # dir DATA ends at 3
    ents += struct.pack(">B", 0) + (6).to_bytes(3, "big") + struct.pack(">II", 0x2800, 4)
    fst = ents + names
    struct.pack_into(">III", img, 0x420, 0x100, 0x1000, len(fst))
    img[0x1000:0x1000 + len(fst)] = fst
    img[0x2800:0x2804] = b"AFS\0"
    p = tmp_path / "gc.iso"
    p.write_bytes(bytes(img))
    return str(p)


def test_gcm_fst_walk(tmp_path):
    ents, info = sgi.walk_gcm_fst(_gcm_fixture(tmp_path))
    files = {e["path"]: e for e in ents if e["path"] != "<boot.dol>"}
    assert files["DATA/A.BIN"]["offset"] == 0x2800 and files["DATA/A.BIN"]["size"] == 4
    assert info["fst_entries"] == 3 and info["dol_offset"] == 0x100


def test_walk_cvm_rejects_non_cvm(tmp_path):
    p = tmp_path / "x.bin"
    p.write_bytes(b"\0" * 0x20000)
    assert sgi.walk_cvm(str(p), 0, 0x20000) is None
