def main():
    paths, missing = {}, []
    for n in sorted(set(MAP.values())):
        try:
            paths[n] = fetch(n)
        except Exception:
            missing.append(n)
    block = runtime(paths)
    for f in ["clients/desktop/index.html", "clients/web/index.html", "clients/desktop/mini.html", "clients/wizard/index.html"]:
        p = ROOT / f
        s = p.read_text(encoding="utf-8")
        s = re.sub(r'<script id="carbon-icons">.*?</script>\n?', "", s, flags=re.S)
        s = s.replace("</head>", block + "\n</head>", 1)
        p.write_text(s, encoding="utf-8", newline="\n")
    print(f"{len(paths)} icons inlined; missing: {missing}")


if __name__ == "__main__":
    main()
