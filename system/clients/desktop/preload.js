const { contextBridge, ipcRenderer } = require("electron");

contextBridge.exposeInMainWorld("gbox", {
  settings: () => ipcRenderer.invoke("settings:get"),
  saveSettings: s => ipcRenderer.invoke("settings:save", s),
  token: () => ipcRenderer.invoke("token"),
  api: (path, body) => ipcRenderer.invoke("api", path, body),
  sparkStatus: () => ipcRenderer.invoke("spark:status"),
  sparkAction: a => ipcRenderer.invoke("spark:action", a),
  winSetup: () => ipcRenderer.invoke("win:setup"),
  winWorker: op => ipcRenderer.invoke("win:worker", op),
  cancel: id => ipcRenderer.invoke("task:cancel", id),
  openExternal: url => ipcRenderer.invoke("open:external", url),
  relaunch: () => ipcRenderer.invoke("app:relaunch"),
  capture: () => ipcRenderer.invoke("capture"),
  embedSync: st => ipcRenderer.invoke("embed:sync", st),
  embedRelease: () => ipcRenderer.invoke("embed:release"),
  stt: buf => ipcRenderer.invoke("stt", buf),
  tts: (text, voice) => ipcRenderer.invoke("tts", text, voice),
  miniOpen: (sid, title) => ipcRenderer.invoke("mini:open", sid, title),
  miniAspect: (w, h) => ipcRenderer.invoke("mini:aspect", w, h),
  miniRestore: () => ipcRenderer.invoke("mini:restore"),
  recStart: ext => ipcRenderer.invoke("rec:start", ext),
  recChunk: buf => ipcRenderer.invoke("rec:chunk", buf),
  recStop: () => ipcRenderer.invoke("rec:stop"),
  recOpen: file => ipcRenderer.invoke("rec:open", file),
  onTask: fn => ipcRenderer.on("task", (_e, id, text) => fn(id, text)),
  onTaskEnd: fn => ipcRenderer.on("task-end", (_e, id, code) => fn(id, code)),
  onWorker: fn => ipcRenderer.on("worker", (_e, running) => fn(running)),
});
