const { contextBridge, ipcRenderer } = require("electron");

contextBridge.exposeInMainWorld("gbox", {
  settings: () => ipcRenderer.invoke("settings:get"),
  saveSettings: s => ipcRenderer.invoke("settings:save", s),
  token: () => ipcRenderer.invoke("token"),
  api: (path, body) => ipcRenderer.invoke("api", path, body),
  sparkStatus: () => ipcRenderer.invoke("spark:status"),
  sparkAction: a => ipcRenderer.invoke("spark:action", a),
  winSetup: () => ipcRenderer.invoke("win:setup"),
  winWorker: op => ipcRenderer.invoke("win:worker", op),
  taskSnapshot: () => ipcRenderer.invoke("task:snapshot"),
  cancel: id => ipcRenderer.invoke("task:cancel", id),
  openExternal: url => ipcRenderer.invoke("open:external", url),
  relaunch: () => ipcRenderer.invoke("app:relaunch"),
  capture: () => ipcRenderer.invoke("capture"),
  captureOS: () => ipcRenderer.invoke("capture:os"),
  consoleTail: n => ipcRenderer.invoke("console:tail", n),
  clipboardFiles: () => ipcRenderer.invoke("report:clipboard-files"),
  embedSync: st => ipcRenderer.invoke("embed:sync", st),
  embedRelease: () => ipcRenderer.invoke("embed:release"),
  stt: buf => ipcRenderer.invoke("stt", buf),
  tts: (text, voice) => ipcRenderer.invoke("tts", text, voice),
  miniOpen: (sid, title) => ipcRenderer.invoke("mini:open", sid, title),
  miniAspect: (w, h) => ipcRenderer.invoke("mini:aspect", w, h),
  miniRestore: () => ipcRenderer.invoke("mini:restore"),
  recStart: (ext, rect) => ipcRenderer.invoke("rec:start", ext, rect),
  recCrop: rect => ipcRenderer.invoke("rec:crop", rect),
  recAbort: () => ipcRenderer.invoke("rec:abort"),
  recScreens: () => ipcRenderer.invoke("rec:screens"),
  recChunk: buf => ipcRenderer.invoke("rec:chunk", buf),
  recStop: () => ipcRenderer.invoke("rec:stop"),
  recFit: (file, o) => ipcRenderer.invoke("rec:fit", file, o),
  recOpen: file => ipcRenderer.invoke("rec:open", file),
  exportPdf: (html, name) => ipcRenderer.invoke("export:pdf", html, name),
  clipImage: dataUrl => ipcRenderer.invoke("clip:image", dataUrl),
  setFullScreen: on => ipcRenderer.invoke("win:fullscreen", on),
  onFullscreen: fn => ipcRenderer.on("fullscreen", (_e, on) => fn(on)),
  updatePending: () => ipcRenderer.invoke("update:pending"),
  browser: (op, url) => ipcRenderer.invoke("browser:send", op, url),
  embedFocus: () => ipcRenderer.invoke("embed:focus"),
  embedKill: () => ipcRenderer.invoke("embed:kill"),
  appFocus: () => ipcRenderer.invoke("app:focus"),
  vizOverlay: st => ipcRenderer.invoke("viz:overlay", st),
  overlay: (op, arg) => ipcRenderer.invoke("overlay", op, arg),
  onOverlay: fn => ipcRenderer.on("overlay:status", (_e, s) => fn(s)),
  onAppFocus: fn => ipcRenderer.on("app-focus", () => fn()),
  onPtt: fn => ipcRenderer.on("ptt", (_e, down) => fn(down)),
  onHotkey: fn => ipcRenderer.on("hotkey", (_e, k) => fn(k)),
  onEmbedEvent: fn => ipcRenderer.on("embed:event", (_e, ev) => fn(ev)),
  onTask: fn => ipcRenderer.on("task", (_e, id, text) => fn(id, text)),
  onTaskEnd: fn => ipcRenderer.on("task-end", (_e, id, code) => fn(id, code)),
  onRecordingCancelled: fn => ipcRenderer.on("recording-cancelled", () => fn()),
  onWorker: fn => ipcRenderer.on("worker", (_e, running) => fn(running)),
  decantPlan: () => ipcRenderer.invoke("decant:plan"),
  decantSave: () => ipcRenderer.invoke("decant:save"),
  decantCancel: () => ipcRenderer.invoke("decant:cancel"),
  decantShow: file => ipcRenderer.invoke("decant:show", file),
  onDecant: fn => ipcRenderer.on("decant", (_e, line) => fn(line)),
  onMenu: fn => ipcRenderer.on("menu", (_e, item) => fn(item)),
});
